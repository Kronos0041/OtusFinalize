import SwiftUI

/// Числовые параметры общих компонентов: размеры, отступы, шрифты, прозрачности и тайминги.
///
/// Константы сгруппированы по компонентам. У каждой описано, где она используется
/// и что изменится на экране, если поменять значение.
enum ComponentConstants {

    // MARK: - Layout

    /// Общая разметка контента каталога.
    enum Layout {
        /// Суммарный горизонтальный отступ ленты категорий и сетки товаров от краёв экрана, 20 pt.
        ///
        /// Используется в `CategoryCollectionView` и `CatalogGridView`: ширина контента — `getWidth() - contentHorizontalInset`.
        /// - Increase: контент сузится, поля по бокам станут шире, карточки в сетке — меньше.
        /// - Decrease: контент прижмётся к краям экрана; при 0 карточки упрутся в края.
        /// - Important: Должна совпадать для ленты и сетки, иначе их края разъедутся.
        static let contentHorizontalInset: CGFloat = 20

        /// Суммарный горизонтальный отступ полей ввода, кнопок и верхней панели от краёв экрана, 40 pt.
        ///
        /// Используется в `ButtonView`, `AuthView`, `CatalogHeaderView` и `MainTopBar`: ширина — `getWidth() - sideInset`.
        /// - Increase: поля и кнопки станут уже.
        /// - Decrease: поля и кнопки прижмутся к краям экрана.
        static let sideInset: CGFloat = 40

        /// Высота основных кнопок (`ButtonView`, кнопка «Добавить» на экране товара), 50 pt.
        ///
        /// - Decrease: меньше 44 pt — в кнопку станет трудно попасть.
        static let buttonHeight: CGFloat = 50
    }

    // MARK: - Animation

    /// Длительности анимаций общих компонентов.
    enum Animation {
        /// Длительность переключения категории, 0.2 с.
        ///
        /// Используется в `CategoryCollectionView`: смена выбранной ячейки и прокрутка ленты к ней.
        /// - Increase: переключение станет плавнее, но при быстрых свайпах по страницам лента будет отставать.
        /// - Decrease: переключение станет резким; при 0 анимации не будет.
        static let categorySwitchDuration: Double = 0.2
    }

    // MARK: - CategoryPicker

    /// Лента категорий над каталогом (`CategoryCollectionView`, `CategoryCollectionCellView`).
    enum CategoryPicker {
        /// Минимальная ширина ячейки категории, 70 pt.
        ///
        /// Ячейки делят ширину экрана поровну, но не становятся уже этого значения.
        /// Когда категорий много, лента начинает прокручиваться.
        /// - Increase: прокрутка появится при меньшем числе категорий.
        /// - Decrease: в экран поместится больше категорий, но длинные названия начнут обрезаться.
        static let minItemWidth: CGFloat = 70

        /// Высота ячейки категории вместе с индикатором, 48 pt.
        ///
        /// - Increase: лента станет выше и сдвинет сетку товаров вниз.
        /// - Decrease: зона нажатия станет меньше рекомендуемых 44 pt.
        static let itemHeight: CGFloat = 48

        /// Расстояние между названием категории и индикатором выбора, 8 pt.
        ///
        /// - Increase: индикатор отойдёт от текста и визуально оторвётся от него.
        /// - Decrease: индикатор прилипнет к тексту.
        static let titleIndicatorSpacing: CGFloat = 8

        /// Толщина линии-индикатора под выбранной категорией, 2 pt.
        ///
        /// - Increase: выбор станет заметнее, линия — тяжелее.
        /// - Decrease: при 1 pt и меньше выбор плохо заметен; при 0 индикатор пропадёт.
        static let indicatorHeight: CGFloat = 2

        /// Размер шрифта названия категории, 16 pt.
        ///
        /// - Increase: длинные названия перестанут помещаться в `minItemWidth`.
        /// - Decrease: названия станут хуже читаться.
        static let fontSize: CGFloat = 16
    }

    // MARK: - Background

    /// Размытый фон стартового экрана и экрана авторизации (`BlurredWallpaperBackground`).
    enum Background {
        /// Прозрачность белого слоя поверх размытых обоев, 0.1.
        ///
        /// - Increase: фон станет светлее и белее, обои будут хуже видны.
        /// - Decrease: обои станут контрастнее, текст поверх них может хуже читаться.
        static let overlayOpacity: Double = 0.1
    }

    // MARK: - StatePlaceholder

    /// Заглушка «пусто / нет сети / ошибка» (`StatePlaceholder`).
    enum StatePlaceholder {
        /// Вертикальное расстояние между иконкой, заголовком, сообщением и кнопкой, 12 pt.
        ///
        /// - Increase: заглушка станет выше и «рыхлее».
        /// - Decrease: элементы слипнутся.
        static let spacing: CGFloat = 12

        /// Размер SF Symbol иконки заглушки, 40 pt.
        ///
        /// - Increase: иконка начнёт доминировать над текстом.
        /// - Decrease: иконка потеряется на пустом экране.
        static let iconSize: CGFloat = 40

        /// Дополнительный отступ над кнопкой «Повторить», 4 pt (добавляется к `spacing`).
        ///
        /// - Increase: кнопка визуально отделится от текста сообщения.
        /// - Decrease: при 0 кнопка встанет на общий `spacing`.
        static let retryTopPadding: CGFloat = 4

        /// Внутренний отступ заглушки от краёв доступной области, 24 pt.
        ///
        /// - Increase: длинный текст сообщения раньше начнёт переноситься.
        /// - Decrease: текст подойдёт вплотную к краям экрана.
        static let padding: CGFloat = 24
    }

    // MARK: - RemoteImage

    /// Загрузка картинки по URL (`RemoteImageView`).
    enum RemoteImage {
        /// Размер иконки-заглушки, когда URL нет или загрузка не удалась, 36 pt.
        ///
        /// Значение по умолчанию; экран может передать своё через `placeholderIconSize`.
        /// - Increase/Decrease: меняет только размер иконки, рамка картинки остаётся прежней.
        static let placeholderIconSize: CGFloat = 36

        /// Пауза между повторными попытками загрузки, 250 мс.
        ///
        /// Число попыток задаётся отдельно через `imageLoadMaxAttempts` в настройках магазина.
        /// - Increase: при нестабильной сети картинка дольше висит в состоянии загрузки, но реже нагружает сервер.
        /// - Decrease: повторы идут почти подряд и при обрыве сети быстро исчерпываются впустую.
        static let retryDelayMilliseconds = 250
    }

    // MARK: - Search

    /// Поле поиска каталога (`SearchTextField`).
    enum Search {
        /// Размер иконки лупы, 20 × 20 pt.
        ///
        /// - Increase: иконка станет крупнее и съест место у текста запроса.
        /// - Decrease: иконка станет плохо различима.
        static let iconSize: CGFloat = 20

        /// Размер кнопки очистки запроса, 28 × 28 pt.
        ///
        /// - Increase: в неё легче попасть, но поле ввода станет уже.
        /// - Decrease: в кнопку станет трудно попасть пальцем.
        static let clearButtonSize: CGFloat = 28

        /// Радиус скругления поля поиска, 10 pt.
        ///
        /// - Increase: при половине высоты поля (25 pt) поле станет «капсулой».
        /// - Decrease: при 0 углы станут прямыми.
        static let cornerRadius: CGFloat = 10
    }

    // MARK: - Button

    /// Основная кнопка на всю ширину (`ButtonView`). Размеры задают `Layout.sideInset` и `Layout.buttonHeight`.
    enum Button {
        /// Размер шрифта заголовка кнопки, 18 pt.
        ///
        /// - Increase: длинные заголовки перестанут помещаться в одну строку.
        /// - Decrease: кнопка станет менее заметной как основное действие.
        static let fontSize: CGFloat = 18

        /// Радиус скругления кнопки, 10 pt.
        ///
        /// - Important: Держи равным `Search.cornerRadius`, чтобы поле и кнопки выглядели одинаково.
        static let cornerRadius: CGFloat = 10
    }

    // MARK: - Bell

    /// Колокольчик уведомлений с бейджем (`BellView`).
    enum Bell {
        /// Размер иконки колокольчика и всего компонента, 30 × 30 pt.
        ///
        /// - Increase: иконка станет крупнее вордмарка и налезет на него в `MainTopBar`.
        /// - Decrease: зона нажатия станет меньше; бейдж начнёт перекрывать иконку.
        static let iconSize: CGFloat = 30

        /// Диаметр круглого бейджа со счётчиком, 20 pt. Радиус скругления — половина этого значения.
        ///
        /// - Increase: бейдж закроет большую часть колокольчика.
        /// - Decrease: «99+» перестанет помещаться в бейдж.
        static let badgeSize: CGFloat = 20

        /// Размер шрифта счётчика в бейдже, 8 pt.
        ///
        /// - Increase: «99+» перестанет помещаться в `badgeSize`.
        /// - Decrease: цифры станут нечитаемыми.
        static let badgeFontSize: CGFloat = 8

        /// Смещение бейджа от правого верхнего угла колокольчика, (3, −8) pt.
        ///
        /// - Increase/Decrease: сдвигает бейдж; при больших значениях он выйдет за пределы
        ///   кнопки и обрежется краем экрана.
        static let badgeOffset = CGSize(width: 3, height: -8)

        /// Максимальное число, которое бейдж показывает целиком, 99. Больше — показывается «99+».
        ///
        /// - Increase: трёхзначные числа не поместятся в `badgeSize`.
        /// - Decrease: «N+» будет показываться уже при небольшом числе уведомлений.
        static let maxBadgeCount = 99
    }

    // MARK: - SizeCollection

    /// Горизонтальный выбор размера товара (`SizeCollection`).
    enum SizeCollection {
        /// Расстояние между ячейками размеров, 12 pt.
        ///
        /// - Increase: в экран поместится меньше размеров без прокрутки.
        /// - Decrease: ячейки слипнутся, обводки сольются.
        static let spacing: CGFloat = 12

        /// Размер шрифта подписи размера, 16 pt.
        ///
        /// - Increase: длинные подписи («XXL», «One size») расширят ячейку.
        /// - Decrease: подписи станут хуже читаться.
        static let fontSize: CGFloat = 16

        /// Горизонтальный внутренний отступ подписи в ячейке, 16 pt.
        ///
        /// - Increase: ячейки с длинными подписями станут шире `minCellWidth`.
        /// - Decrease: длинная подпись подойдёт вплотную к обводке.
        static let horizontalPadding: CGFloat = 16

        /// Минимальная ширина ячейки, 52 pt, — короткие размеры («S», «M») получают одинаковую ширину.
        ///
        /// - Increase: ячейки станут шире, в экран поместится меньше.
        /// - Decrease: ячейки «S» и «XL» станут разной ширины.
        static let minCellWidth: CGFloat = 52

        /// Минимальная высота ячейки, 50 pt.
        ///
        /// - Decrease: меньше 44 pt — зона нажатия станет меньше рекомендуемой.
        static let minCellHeight: CGFloat = 50

        /// Радиус скругления обводки ячейки, 8 pt.
        ///
        /// - Increase: ячейки станут более «круглыми».
        /// - Decrease: при 0 углы станут прямыми.
        static let cornerRadius: CGFloat = 8

        /// Толщина обводки ячейки, 1 pt.
        ///
        /// - Increase: обводка станет тяжелее и выйдет за `borderInset`.
        /// - Decrease: при 0 у невыбранных ячеек пропадут границы.
        static let borderWidth: CGFloat = 1

        /// Прозрачность цвета обводки, 0.3.
        ///
        /// - Increase: обводка станет контрастнее.
        /// - Decrease: невыбранные ячейки сольются с фоном.
        static let borderOpacity: Double = 0.3

        /// Отступ содержимого внутри `ScrollView`, 1 pt.
        ///
        /// Нужен, чтобы `ScrollView` не обрезал обводку крайних ячеек.
        /// - Important: Должен быть не меньше `borderWidth`, иначе края обводки обрежутся.
        static let borderInset: CGFloat = 1
    }

    // MARK: - TopBar

    /// Верхние панели: главная (`MainTopBar`) и панель экрана товара (`TopBarDescriptionView`).
    enum TopBar {
        /// Размер иконки «назад» в `TopBarDescriptionView`, 25 × 25 pt (вместе с `padding()` зона нажатия ≈ 57 pt).
        ///
        /// - Increase: иконка станет крупнее заголовка.
        /// - Decrease: иконку станет трудно различить.
        static let backIconSize: CGFloat = 25

        /// Размер шрифта заголовка в `TopBarDescriptionView`, 24 pt.
        ///
        /// - Increase: длинные заголовки залезут под кнопку «назад».
        /// - Decrease: заголовок перестанет читаться как заголовок экрана.
        static let titleFontSize: CGFloat = 24

        /// Высота `MainTopBar`, 56 pt.
        ///
        /// - Increase: панель сдвинет каталог вниз.
        /// - Decrease: меньше 44 pt — кнопка колокольчика обрежется.
        static let mainHeight: CGFloat = 56

        /// Размер рамки вордмарка по центру `MainTopBar`, 160 × 40 pt (картинка вписывается с сохранением пропорций).
        ///
        /// - Increase: вордмарк может налезть на колокольчик справа на узких экранах.
        /// - Decrease: бренд станет плохо читаться.
        static let wordmarkSize = CGSize(width: 160, height: 40)
    }
}
